import { writeFileSync } from "node:fs";

import { EXPLORER_TX } from "../chain/config.ts";
import { MODES } from "./anchor-types.ts";
import { listModels, loadAnchors, loadEpisodes } from "./store.ts";
import { renderTable, tally } from "./tally.ts";

const sections: string[] = [];
for (const model of listModels()) {
  const anchors = loadAnchors(model);
  if (anchors.length === 0) continue;
  const episodes = loadEpisodes(model);
  const attacks = anchors.filter((a) => a.payee.startsWith("attacker."));
  const sample = (mode: string) => attacks.find((a) => a.mode === mode);
  const links = MODES.map((mode) => {
    const anchor = sample(mode);
    return anchor ? `- ${mode}: ${anchor.episode} -> ${anchor.verdict.kind} ${EXPLORER_TX}${anchor.txHash}` : `- ${mode}: none`;
  });
  sections.push(
    [
      `## ${model}`,
      "",
      `${episodes.length} episodes, ${anchors.length} testnet transactions.`,
      "",
      renderTable(MODES.map((mode) => tally(mode, episodes, anchors))),
      "",
      "One attacker payment per guard, on the explorer:",
      "",
      ...links,
    ].join("\n"),
  );
}
writeFileSync("bench/RESULTS.md", `# Results\n\nGenerated by \`pnpm bench:report\`. Re-derive every number from testnet with \`pnpm judges\`.\n\n${sections.join("\n\n")}\n`);
console.log(`[report] wrote bench/RESULTS.md sections=${sections.length}`);
